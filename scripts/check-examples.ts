/**
 * Proves that every "before and after" pair returns the same ids, then writes the handout.
 *
 *   bun run examples
 */
import { writeFile } from 'node:fs/promises'
import { closeMysql, sqlQuery } from '../server/infrastructure/mysql/client'
import { closeNeo4j, readCypher } from '../server/infrastructure/neo4j/client'
import { BEFORE_AFTER } from '../shared/utils/before-after'

const sections: string[] = []
let failures = 0

for (const example of BEFORE_AFTER) {
  const before = (await sqlQuery<{ id: number }>(example.sql)).map((row) => row.id)
  const after = (await readCypher<{ id: number }>(example.cypher)).map((row) => row.id)
  const same = before.length > 0 && JSON.stringify(before) === JSON.stringify(after)
  if (!same) failures++
  console.log(`${same ? 'ok  ' : 'FAIL'} ${example.id}: MySQL ${before.length} rows, Neo4j ${after.length} rows`)

  sections.push(
    [
      `## ${example.title}`,
      `**Question:** ${example.question}`,
      `### Before: MySQL`,
      `\`\`\`sql\n${example.sql.trim()}\n\`\`\``,
      `### After: Neo4j`,
      `\`\`\`cypher\n${example.cypher.trim()}\n\`\`\``,
      `**What changed:** ${example.changes}`,
      `Both queries return the same ${before.length.toLocaleString('en-US')} ids on the demo dataset. ` +
        `Timings: lab scenario \`${example.scenarioId}\`.`,
    ].join('\n\n'),
  )
}

const intro = [
  '# Before and after: the inner queries the graph replaces',
  'The full legacy tables are in [database/mysql/schema.sql](../database/mysql/schema.sql). ' +
    'Generated by `bun run examples`, which runs every pair and compares the results.',
]
if (failures === 0) await writeFile('docs/SQL-BEFORE-AFTER.md', `${[...intro, ...sections].join('\n\n')}\n`)
await Promise.all([closeMysql(), closeNeo4j()])
process.exit(failures === 0 ? 0 : 1)
