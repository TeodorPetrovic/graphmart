import type {
  BenchmarkReport,
  EngineId,
  EngineRunResult,
  ExplainResponse,
  RunScenarioResponse,
  ScenarioInfo,
} from '../../../shared/types/api'

const ENGINES: { id: EngineId; name: string }[] = [
  { id: 'mysql', name: 'MySQL' },
  { id: 'mongo', name: 'MongoDB' },
  { id: 'neo4j', name: 'Neo4j' },
]

export interface ScenarioNotes {
  info: ScenarioInfo
  explains: ExplainResponse[]
}

function timing(result: EngineRunResult | undefined): string {
  if (!result) return '—'
  if (result.timedOut) return 'timeout (>15 s)'
  return result.ok ? `${result.medianMs?.toFixed(2)} ms` : 'error'
}

/** "Neo4j 8.4×" means the fastest engine, and how much slower the slowest successful one was. */
function verdict(run: RunScenarioResponse): string {
  const finished = run.results.filter((result) => result.medianMs !== null).sort((a, b) => a.medianMs! - b.medianMs!)
  const fastest = finished[0]
  const slowest = finished.at(-1)
  if (!fastest || !slowest || fastest === slowest) return '—'
  const name = ENGINES.find((engine) => engine.id === fastest.engine)!.name
  const ratio = slowest.medianMs! / Math.max(fastest.medianMs!, 0.01)
  return ratio < 1.2 ? 'about equal' : `${name} ${ratio.toFixed(1)}×`
}

function timingRow(label: string, run: RunScenarioResponse): string {
  const cells = ENGINES.map(({ id }) => timing(run.results.find((result) => result.engine === id)))
  const match = run.resultsMatch === null ? '—' : run.resultsMatch ? 'yes' : '**NO**'
  return `| ${label} | ${cells.join(' | ')} | ${verdict(run)} | ${match} |`
}

const tableHeader = (first: string) =>
  [`| ${first} | MySQL | MongoDB | Neo4j | Fastest (vs slowest) | Same rows |`, '|---|---:|---:|---:|---|:---:|'].join(
    '\n',
  )

function scenarioSection({ info, explains }: ScenarioNotes): string {
  const engines = info.engines.map((engine) => {
    const metrics = explains.find((explain) => explain.engine === engine.engine)?.metrics ?? []
    return [
      `#### ${ENGINES.find((item) => item.id === engine.engine)!.name}: ${engine.label}`,
      `\`\`\`${engine.language}\n${engine.query}\n\`\`\``,
      ...engine.notes.map((note) => `- ${note}`),
      metrics.length ? `\n**Plan:** ${metrics.map((metric) => `${metric.label}: ${metric.value}`).join(' · ')}` : '',
    ].join('\n')
  })
  return [
    `### ${info.order}. ${info.title}`,
    `**Question:** ${info.question}`,
    `**Why it hurts in tables:** ${info.relationalPain}`,
    `**What changes:** ${info.nosqlWin}`,
    ...engines,
  ].join('\n\n')
}

export function renderReport(report: BenchmarkReport, notes: ScenarioNotes[]): string {
  const lectures = ([1, 2] as const).map((lecture) => {
    const inLecture = notes.filter(({ info }) => info.lecture === lecture)
    const rows = inLecture.flatMap(({ info }) => {
      const run = report.results.find((result) => result.scenarioId === info.id)
      return run ? [timingRow(info.title, run)] : []
    })
    return [
      `## Lecture ${lecture}`,
      [tableHeader('Scenario'), ...rows].join('\n'),
      ...inLecture.map(scenarioSection),
    ].join('\n\n')
  })

  const scaling = (report.scaling ?? []).map((run) => {
    const label = `${run.scenarioId} (${Object.entries(run.params)
      .map(([key, value]) => `${key}=${value}`)
      .join(', ')})`
    return timingRow(label, run)
  })

  return [
    '# GraphMart benchmarks: MySQL before, MongoDB and Neo4j after',
    `Generated by \`bun run bench\` on ${report.generatedAt}. Machine: ${report.machine}. Dataset: **${report.scale}**. ` +
      `Median of ${report.iterations} runs after one warm-up, one engine at a time, each database with about 1 GB of cache. ` +
      'These are measurements of this machine and dataset, not universal numbers.',
    '## How cost grows with depth',
    [tableHeader('Scenario'), ...scaling].join('\n'),
    ...lectures,
    '',
  ].join('\n\n')
}
